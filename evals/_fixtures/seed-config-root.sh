#!/usr/bin/env bash
# Seeds a small, fictional Nucleus config root for eval runs and points the
# run's temporary home at it. Run by `claude plugin eval --scaffold`.
# Everything here is invented; it contains no real people, clients, or data.
set -euo pipefail

ROOT="$PWD/cortex-root"
TODAY="$(date +%Y-%m-%d)"
YESTERDAY="$(date -v-1d +%Y-%m-%d 2>/dev/null || date -d yesterday +%Y-%m-%d)"

mkdir -p "$ROOT/memory/client" "$ROOT/memory/me" \
         "$ROOT/memory/staged/commit-drafts" "$ROOT/archive/$YESTERDAY" \
         "$ROOT/plugins" "$ROOT/briefs" "$HOME/.cortex"
printf '%s\n' "$ROOT" > "$HOME/.cortex/config-root"

cat > "$ROOT/memory/CLAUDE.md" <<EOF
# Working memory (eval fixture)

Start with \`hot.md\`, then \`DASHBOARD.md\` and \`index.md\`.

## Autonomy policy
Unattended runs stage cited proposals; they never edit durable memory.
EOF

cat > "$ROOT/memory/me/identity.md" <<EOF
# Identity
- Actor ID: sample-user
- Name: Sample User
- Company: Example Studio
- Time zone: America/New_York
EOF

cat > "$ROOT/memory/hot.md" <<EOF
# Hot cache

_Last refreshed: $YESTERDAY 23:10 by listen._
_Rolling window: last 7 days._

## What I worked on (last 7 days)
- $YESTERDAY — [[client/northwind]]: Kickoff call held; agreed a two-phase pilot. [by:sample-user]

## Active threads (open, modified in last 7 days)
- [[client/northwind]] — **[P0]** Send the pilot scope summary to Dana Reyes by Friday.
- [[client/northwind]] — **[WAITING:Dana Reyes]** Sample course files.
- [[ops/hiring]] — **[P1]** Review two contractor applications.
EOF

cat > "$ROOT/memory/DASHBOARD.md" <<EOF
# Working Memory Dashboard
> Last updated: $YESTERDAY

## Active Nodes (updated ≤14 days)
### [[client/northwind]]
Two-phase pilot agreed at kickoff. Scope summary owed to Dana Reyes.
### [[ops/hiring]]
Two contractor applications waiting for review.
EOF

cat > "$ROOT/memory/index.md" <<EOF
# Memory index
## client
- [[client/northwind]] — active
## ops
- [[ops/hiring]] — active
EOF

cat > "$ROOT/memory/client/northwind.md" <<EOF
---
type: client
status: active
---
# Northwind Learning

## Current state
Two-phase pilot agreed at kickoff on $YESTERDAY.

## Open threads
- **[P0]** Send the pilot scope summary to Dana Reyes by Friday.

## Waiting on
- **[WAITING:Dana Reyes]** Sample course files.

## Changelog
- [$YESTERDAY] Kickoff call held.
EOF

mkdir -p "$ROOT/memory/ops"
cat > "$ROOT/memory/ops/hiring.md" <<EOF
---
type: ops
status: active
---
# Hiring

## Open threads
- **[P1]** Review two contractor applications.
EOF

cat > "$ROOT/archive/$YESTERDAY/_index.md" <<EOF
# Archive index — $YESTERDAY
## Counts
- calendar: 2 events
- transcripts: 1
EOF

cat > "$ROOT/archive/$YESTERDAY/transcript-northwind-kickoff.md" <<EOF
# Northwind kickoff — $YESTERDAY
Dana Reyes: We can share sample course files next week.
Sample User: I will send the pilot scope summary by Friday.
Dana Reyes: Budget for phase one is approved; phase two depends on the pilot results.
EOF

cat > "$ROOT/memory/staged/commit-drafts/$YESTERDAY.md" <<EOF
# Commit draft — $YESTERDAY

Generated by /listen at ${YESTERDAY}T23:10:00-05:00.
Total proposals: 2 across 1 nodes.

## Summary
- 1 proposed knowledge entries
- 0 proposed person-page updates
- 1 proposed commitments
- 0 proposed thread updates / closures

## Proposals

### Proposal 1 — client/northwind: phase-one budget approved
- **Type:** INSIGHT
- **From:** note-taker (mode: transcript)
- **Source:** archive/$YESTERDAY/transcript-northwind-kickoff.md (line 4)
- **Proposed content:**
  > Phase-one budget is approved; phase two depends on the pilot results.
- **Target placement:** \`client/northwind\` · section \`Knowledge\`
- **Confidence:** high
- **Conflicts:** none

### Proposal 2 — client/northwind: scope summary owed
- **Type:** commitment
- **From:** note-taker (mode: transcript)
- **Source:** archive/$YESTERDAY/transcript-northwind-kickoff.md (line 3)
- **Proposed content:**
  > Send the pilot scope summary to Dana Reyes by Friday.
- **Target placement:** \`client/northwind\` · section \`Open threads\`
- **Confidence:** high
- **Conflicts:** already present as an open P0 thread
EOF
