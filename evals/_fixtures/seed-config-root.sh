#!/usr/bin/env bash
# Seeds a small, fictional Nucleus config root for eval runs and points the
# run's temporary home at it. Run by `claude plugin eval --scaffold`.
# Everything here is invented; it contains no real people, clients, or data.
set -euo pipefail

ROOT="$PWD/cortex-root"
TODAY="$(date +%Y-%m-%d)"
YESTERDAY="$(date -v-1d +%Y-%m-%d 2>/dev/null || date -d yesterday +%Y-%m-%d)"
QUIET_SINCE="$(date -v-20d +%Y-%m-%d 2>/dev/null || date -d '20 days ago' +%Y-%m-%d)"
LAST_WEEK="$(date -v-6d +%Y-%m-%d 2>/dev/null || date -d '6 days ago' +%Y-%m-%d)"

mkdir -p "$ROOT/memory/client" "$ROOT/memory/me" \
         "$ROOT/memory/staged/commit-drafts" "$ROOT/archive/$YESTERDAY/transcripts" \
         "$ROOT/plugins" "$ROOT/briefs" "$HOME/.cortex"
printf '%s\n' "$ROOT" > "$HOME/.cortex/config-root"

cat > "$ROOT/memory/CLAUDE.md" <<EOF
# Working memory (eval fixture)

Start with \`hot.md\`, then \`DASHBOARD.md\` and \`index.md\`.

## Autonomy policy
Unattended runs stage cited proposals; they never edit durable memory.
EOF

cat > "$ROOT/memory/me/identity.md" <<EOF
# Identity
- Actor ID: sample-user
- Name: Sample User
- Company: Example Studio
- Time zone: America/New_York
EOF

cat > "$ROOT/memory/hot.md" <<EOF
# Hot cache

_Last refreshed: $YESTERDAY 23:10 by listen._
_Rolling window: last 7 days._

## What I worked on (last 7 days)
- $YESTERDAY — [[client/northwind]]: Kickoff call held; agreed a two-phase pilot. [by:sample-user]

## Active threads (open, modified in last 7 days)
- [[client/northwind]] — **[P0]** Send the pilot scope summary to Dana Reyes by Friday.
- [[client/northwind]] — **[WAITING:Dana Reyes]** Sample course files.
- [[ops/hiring]] — **[P1]** Review two contractor applications.
EOF

cat > "$ROOT/memory/DASHBOARD.md" <<EOF
# Working Memory Dashboard
> Last updated: $YESTERDAY

## Active Nodes (updated ≤14 days)
### [[client/northwind]]
Two-phase pilot agreed at kickoff. Scope summary owed to Dana Reyes.
