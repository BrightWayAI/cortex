from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from scripts.lib import nudges_review as nr  # noqa: E402


def nudge(n: int, key: str, subject: str = "Northwind", draft: str = "Hi Dana, checking in on the pilot.") -> str:
    return (
        f"### Nudge {n} — {subject}\n"
        "- **Trigger:** stale-deal\n"
        f"- **Key:** {key}\n"
        "- **Quiet since:** 2026-10-27\n"
        "- **Days quiet:** 20 days\n"
        "- **Source:** crm:101\n"
        "- **Draft:**\n"
        f"  > {draft}\n\n"
    )


def day_file(*nudges: str) -> str:
    return "# Nudges — x\n\nGenerated by /nudges.\n\n" + "".join(nudges)


def line(key: str, event: str, ts: str, **extra) -> str:
    return json.dumps({"ts": ts, "key": key, "event": event, "by": "sample-user", **extra}) + "\n"


class Base(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        self.dir = self.root / "memory" / "staged" / "nudges"
        self.dir.mkdir(parents=True)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def write(self, name: str, text: str) -> None:
        (self.dir / name).write_text(text, encoding="utf-8")

    def keys(self) -> list[str]:
        return [i["key"] for i in nr.open_nudges(self.dir)["open"]]


class OpenNudges(Base):
    def test_no_folder_means_nothing_open(self) -> None:
        r = nr.open_nudges(self.root / "nope")
        self.assertEqual((r["open"], r["archivable"], r["summary"]), ([], [], {"open": 0, "files": 0}))

    def test_flagged_items_are_open_and_drafts_are_not_in_the_report(self) -> None:
        self.write("2026-11-16.md", day_file(nudge(1, "stale-deal:101"), nudge(2, "no-reply:t9", "Re: pilot")))
        self.write("ledger.jsonl", line("stale-deal:101", "flagged", "2026-11-16T06:30:00-05:00", as_of="2026-10-27"))
        r = nr.open_nudges(self.dir)
        self.assertEqual([i["key"] for i in r["open"]], ["stale-deal:101", "no-reply:t9"])
        self.assertEqual(r["open"][0], {"file": "2026-11-16.md", "number": 1, "key": "stale-deal:101", "trigger": "stale-deal",
                                        "subject": "Northwind", "quiet_since": "2026-10-27", "days_quiet": "20 days", "has_draft": True})
        self.assertNotIn("checking in", json.dumps(r))
        self.assertEqual(r["archivable"], [])

    def test_acted_snoozed_and_dismissed_close_an_item(self) -> None:
        self.write("2026-11-16.md", day_file(nudge(1, "a:1"), nudge(2, "a:2"), nudge(3, "a:3"), nudge(4, "a:4")))
        self.write("ledger.jsonl", line("a:1", "acted", "2026-11-16T09:00:00") + line("a:2", "snoozed", "2026-11-17", until="2026-12-01")
                   + line("a:3", "dismissed", "2026-11-16"))
        self.assertEqual(self.keys(), ["a:4"])

    def test_a_close_from_before_the_file_does_not_hide_a_new_flag(self) -> None:
        self.write("2026-11-16.md", day_file(nudge(1, "a:1")))
        self.write("ledger.jsonl", line("a:1", "acted", "2026-10-20"))
        self.assertEqual(self.keys(), ["a:1"])

    def test_fully_handled_file_is_archivable_and_partly_handled_is_not(self) -> None:
        self.write("2026-11-13.md", day_file(nudge(1, "a:1")))
        self.write("2026-11-16.md", day_file(nudge(1, "b:1"), nudge(2, "b:2")))
        self.write("ledger.jsonl", line("a:1", "acted", "2026-11-14") + line("b:1", "dismissed", "2026-11-16"))
        r = nr.open_nudges(self.dir)
        self.assertEqual(r["archivable"], ["2026-11-13.md"])
        self.assertEqual([i["key"] for i in r["open"]], ["b:2"])

    def test_a_key_in_two_files_is_shown_once_from_the_newest(self) -> None:
        self.write("2026-11-01.md", day_file(nudge(1, "a:1")))
        self.write("2026-11-16.md", day_file(nudge(1, "a:1")))
        r = nr.open_nudges(self.dir)
        self.assertEqual([(i["key"], i["file"]) for i in r["open"]], [("a:1", "2026-11-16.md")])
        self.assertEqual(r["archivable"], ["2026-11-01.md"])

    def test_item_without_a_key_stays_visible(self) -> None:
        self.write("2026-11-16.md", "### Nudge 1 — Mystery\n- **Trigger:** stale-deal\n- **Draft:** none — needs the file\n")
        r = nr.open_nudges(self.dir)
        self.assertEqual((len(r["open"]), r["open"][0]["has_draft"], r["archivable"]), (1, False, []))

    def test_draft_none_is_reported_as_no_draft(self) -> None:
        self.write("2026-11-16.md", day_file(nudge(1, "a:1", draft="none — needs the pricing sheet")))
        self.assertFalse(nr.open_nudges(self.dir)["open"][0]["has_draft"])

    def test_other_files_and_bad_ledger_lines_are_ignored(self) -> None:
        self.write("2026-11-16.md", day_file(nudge(1, "a:1")))
        self.write("notes.md", day_file(nudge(1, "z:9")))
        self.write("ledger.jsonl", "not json\n[1]\n" + line("a:1", "acted", "garbage") + line("a:1", "flagged", "2026-11-16"))
        self.assertEqual(self.keys(), ["a:1"])
        self.assertEqual(nr.open_nudges(self.dir)["files"], ["2026-11-16.md"])


class Cli(Base):
    def test_cli_is_read_only(self) -> None:
        self.write("2026-11-16.md", day_file(nudge(1, "a:1")))
        before = sorted(p.name for p in self.dir.iterdir())
        out = subprocess.run([sys.executable, str(REPO / "scripts" / "cortex_cli.py"), "open-nudges", "--config-root", str(self.root)],
                             capture_output=True, text=True)
        self.assertEqual(out.returncode, 0, out.stderr)
        self.assertEqual(json.loads(out.stdout)["summary"], {"open": 1, "files": 1})
        self.assertEqual(sorted(p.name for p in self.dir.iterdir()), before)


if __name__ == "__main__":
    unittest.main()
